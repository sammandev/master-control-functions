-- MCP catalog contract (ADR-0012). Script grammar and script-key audits are
-- web-native: keyed by the Function natural key so they survive workbook
-- import/reset (sequences/devices precedent) and are not exported.

CREATE TABLE function_grammars (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    function_source TEXT NOT NULL,
    function_interface TEXT NOT NULL,
    function_name TEXT NOT NULL,
    encoding TEXT NOT NULL CHECK (encoding IN ('raw', 'named')),
    scope TEXT NOT NULL CHECK (scope IN ('line', 'bundle')),
    audited_by TEXT NOT NULL CHECK (audited_by <> ''),
    audited_at TEXT NOT NULL,
    note TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    UNIQUE (function_source, function_interface, function_name)
);

CREATE TABLE script_key_audits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    function_source TEXT NOT NULL,
    function_interface TEXT NOT NULL,
    function_name TEXT NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('parameter', 'criterion')),
    name TEXT NOT NULL CHECK (name <> ''),
    scope TEXT NOT NULL CHECK (scope IN ('line', 'bundle')),
    audited_by TEXT NOT NULL CHECK (audited_by <> ''),
    audited_at TEXT NOT NULL,
    note TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    UNIQUE (function_source, function_interface, function_name, kind, name)
);


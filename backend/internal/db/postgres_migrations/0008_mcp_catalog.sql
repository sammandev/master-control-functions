-- No CHECK constraints on definition vocabulary: the source workbook itself
-- carries values outside it, and constraints (even NOT VALID) would make its
-- import fail. MCP readiness and docs/sql/mcp-catalog-report.sql report them.

-- Read-only contract for script-audit-mcp. Links and examples carry no
-- interface, so function_interface is inferred only when (source, name) names
-- exactly one Function; '' means ambiguous or orphaned.
CREATE VIEW mcp_v1_functions AS
SELECT f.id, f.source, f.interface, f.name, f.description, f.convention,
       f.category, f.execution_role, f.execution_phase,
       COALESCE(g.encoding, '') AS grammar_encoding,
       COALESCE(g.scope, '') AS grammar_scope
FROM functions f
LEFT JOIN function_grammars g
       ON g.function_source = f.source
      AND g.function_interface = f.interface
      AND g.function_name = f.name;

CREATE VIEW mcp_v1_parameter_definitions AS
SELECT id, name, device_name, description, type, unit, default_value,
       allowed_values, cardinality, value_pattern, required
FROM parameter_definitions;

CREATE VIEW mcp_v1_criteria_definitions AS
SELECT id, name, device_name, description, type, unit, default_value,
       allowed_values, cardinality, value_pattern, required
FROM criteria_definitions;

CREATE VIEW mcp_v1_parameter_links AS
SELECT l.id, l.name, l.function_source, l.function_name, l.device_name,
       l.position, l.required,
       COALESCE((SELECT MIN(f.interface) FROM functions f
                 WHERE f.source = l.function_source AND f.name = l.function_name
                 HAVING COUNT(*) = 1), '') AS function_interface
FROM parameter_links l;

CREATE VIEW mcp_v1_criteria_links AS
SELECT l.id, l.name, l.function_source, l.function_name, l.device_name,
       l.position, l.required,
       COALESCE((SELECT MIN(f.interface) FROM functions f
                 WHERE f.source = l.function_source AND f.name = l.function_name
                 HAVING COUNT(*) = 1), '') AS function_interface
FROM criteria_links l;

CREATE VIEW mcp_v1_examples AS
SELECT e.id, e.function_source, e.function_name, e.device_name, e.script, e.meaning,
       COALESCE((SELECT MIN(f.interface) FROM functions f
                 WHERE f.source = e.function_source AND f.name = e.function_name
                 HAVING COUNT(*) = 1), '') AS function_interface
FROM examples e;

CREATE VIEW mcp_v1_script_key_audits AS
SELECT function_source, function_interface, function_name, kind, name, scope
FROM script_key_audits;

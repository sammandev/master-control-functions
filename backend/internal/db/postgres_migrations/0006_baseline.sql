CREATE TABLE functions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source TEXT NOT NULL,
    interface TEXT NOT NULL,
    name TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    convention BIGINT,
    category TEXT NOT NULL DEFAULT '',
    execution_role TEXT NOT NULL DEFAULT '',
    execution_phase TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    UNIQUE (source, interface, name)
);
CREATE INDEX idx_functions_name ON functions (name);
CREATE INDEX idx_functions_interface ON functions (interface);

CREATE TABLE parameter_definitions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    type TEXT NOT NULL DEFAULT 'string',
    unit TEXT NOT NULL DEFAULT '',
    default_value TEXT,
    allowed_values TEXT NOT NULL DEFAULT '',
    cardinality TEXT NOT NULL DEFAULT 'SINGLE',
    value_pattern TEXT NOT NULL DEFAULT '',
    required BIGINT NOT NULL DEFAULT 0,
    device_name TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    UNIQUE (name, device_name)
);
CREATE TABLE criteria_definitions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    type TEXT NOT NULL DEFAULT 'string',
    unit TEXT NOT NULL DEFAULT '',
    default_value TEXT,
    allowed_values TEXT NOT NULL DEFAULT '',
    cardinality TEXT NOT NULL DEFAULT 'SINGLE',
    value_pattern TEXT NOT NULL DEFAULT '',
    required BIGINT NOT NULL DEFAULT 0,
    device_name TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    UNIQUE (name, device_name)
);
CREATE TABLE parameter_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    function_source TEXT NOT NULL,
    function_name TEXT NOT NULL,
    device_name TEXT NOT NULL DEFAULT '',
    name TEXT NOT NULL,
    position BIGINT,
    required BIGINT NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    source_file TEXT NOT NULL DEFAULT '',
    UNIQUE (function_source, function_name, device_name, name)
);
CREATE TABLE criteria_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    function_source TEXT NOT NULL,
    function_name TEXT NOT NULL,
    device_name TEXT NOT NULL DEFAULT '',
    name TEXT NOT NULL,
    position BIGINT,
    required BIGINT NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    source_file TEXT NOT NULL DEFAULT '',
    UNIQUE (function_source, function_name, device_name, name)
);
CREATE INDEX idx_parameter_links_name ON parameter_links (name);
CREATE INDEX idx_criteria_links_name ON criteria_links (name);
CREATE INDEX idx_parameter_links_function ON parameter_links (function_source, function_name);
CREATE INDEX idx_criteria_links_function ON criteria_links (function_source, function_name);

CREATE TABLE examples (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    function_source TEXT NOT NULL,
    function_name TEXT NOT NULL,
    device_name TEXT NOT NULL DEFAULT '',
    script TEXT NOT NULL,
    meaning TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    UNIQUE (function_source, function_name, device_name, script)
);
CREATE INDEX idx_examples_function ON examples (function_source, function_name);

CREATE TABLE import_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name TEXT NOT NULL,
    reset BIGINT NOT NULL DEFAULT 0,
    started_at TEXT NOT NULL,
    finished_at TEXT NOT NULL,
    counts TEXT NOT NULL DEFAULT '{}',
    skipped TEXT NOT NULL DEFAULT '[]'
);
CREATE TABLE import_normalizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES import_runs (id),
    table_name TEXT NOT NULL,
    row_key TEXT NOT NULL,
    column_name TEXT NOT NULL,
    source_value TEXT NOT NULL,
    normalized_value TEXT NOT NULL,
    rule TEXT NOT NULL
);
CREATE INDEX idx_import_normalizations_run ON import_normalizations (run_id);

CREATE TABLE sequences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    description TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE TABLE sequence_steps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sequence_id BIGINT NOT NULL REFERENCES sequences (id) ON DELETE CASCADE,
    position BIGINT NOT NULL,
    function_source TEXT NOT NULL,
    function_interface TEXT NOT NULL,
    function_name TEXT NOT NULL,
    parameters TEXT NOT NULL DEFAULT '{}',
    criteria TEXT NOT NULL DEFAULT '{}',
    timeout_ms TEXT NOT NULL DEFAULT '',
    flow TEXT NOT NULL DEFAULT '',
    on_fail TEXT NOT NULL DEFAULT '',
    device_name TEXT NOT NULL DEFAULT '',
    note TEXT NOT NULL DEFAULT ''
);
CREATE INDEX idx_sequence_steps_sequence ON sequence_steps (sequence_id, position);

CREATE TABLE devices (
    name TEXT NOT NULL UNIQUE CHECK (name <> ''),
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);